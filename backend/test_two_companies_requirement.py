    print("=" * 80)
    
    payload = {
        "assignment_text": assignment_text,
        "student_text": student_text_one_company
    }
    
    try:
        response = requests.post(
            f"{BACKEND_URL}/api/v1/assessment/forensic-grade-v3",
            json=payload,
            timeout=120
        )
        
        if response.status_code == 200:
            result = response.json()
            print(f"\n✅ النتيجة النهائية: {result.get('final_grade')}")
            
            # فحص معيار D1
            d1_result = result.get('criteria', {}).get('D1', {})
            print(f"\n📊 تقييم المعيار D1:")
            print(f"   - تحقق: {'✅ نعم' if d1_result.get('achieved') else '❌ لا'}")
            print(f"   - التبرير: {d1_result.get('reasoning', 'N/A')[:200]}...")
            
            # فحص quantitative_check
            quant_check = d1_result.get('quantitative_check')
            if quant_check:
                print(f"\n🔢 التحقق الكمي:")
                print(f"   - المطلوب: {quant_check.get('required', 'N/A')}")
                print(f"   - ما وجده: {quant_check.get('found', 'N/A')}")
                print(f"   - مستوفى: {'✅ نعم' if quant_check.get('satisfied') else '❌ لا'}")
            
            # التحقق من النتيجة المتوقعة
            if d1_result.get('achieved'):
                print("\n❌ فشل الاختبار: المعيار D1 نجح رغم أن الطالب ذكر شركة واحدة فقط!")
            else:
                print("\n✅ نجح الاختبار: المعيار D1 فشل كما هو متوقع (شركة واحدة فقط)")
        else:
            print(f"❌ خطأ: {response.status_code} - {response.text[:300]}")
            
    except Exception as e:
        print(f"❌ خطأ: {e}")

