# ──────────────────────────────────────────────────────
PASS_EXEMPLAR_AR = """\
مثال حقيقي على إجابة حققت مستوى PASS  (صِف / وضِّح):
────────────────────────────────────────────────────────
السياق: طُلب من الطالب أن يصف الطرق المختلفة لتقديم خدمة العملاء في شركته.

[ما كتبه الطالب — هذا النص هو PASS نظيف]:
"خدمة الفروع المباشرة: يعتمد البنك على شبكة واسعة من الفروع المنتشرة في جميع
محافظات الأردن لتقديم خدمة عملاء شخصية. يمكن للعملاء التواصل مباشرة مع موظفين
مؤهلين سواء لفتح حسابات أو الحصول على تمويل أو تلقي استشارات مالية متخصصة.
توفر هذه الطريقة للعميل تجربة تفاعلية وشخصية مما يعزز الثقة بين العميل والبنك،
كما تتيح للموظفين ملاحظة احتياجات العملاء مباشرة والاستجابة لمشاكلهم بسرعة
مما يساهم في زيادة رضا العملاء."

📌 لماذا هذا يستحق PASS:
  ✓ وصف محدد وواضح للطريقة (شبكة الفروع المباشرة)
  ✓ تفاصيل كافية (47 فرع، جميع المحافظات، موظفون مؤهلون)
  ✓ أمثلة ملموسة من سياق الشركة (فتح حسابات، تمويل، استشارات)
  ✓ يبيّن الدور والأثر (يعزز الثقة، يزيد رضا العملاء)
  ✗ لا يحلل السبب أو يكشف العلاقات العميقة (هذا كافٍ للـ PASS فقط)
────────────────────────────────────────────────────────"""

# ──────────────────────────────────────────────────────
# MERIT — مثال حقيقي من M.1 (تحليل تأثير التشريعات — البنك)
# ──────────────────────────────────────────────────────
MERIT_EXEMPLAR_AR = """\
مثال حقيقي على إجابة حققت مستوى MERIT  (حلِّل / ناقش / فسِّر السبب):
────────────────────────────────────────────────────────
السياق: طُلب من الطالب أن يحلل كيف تؤثر التشريعات واللوائح على خدمة العملاء.

[ما كتبه الطالب — هذا النص هو MERIT]:
"تؤثر لوائح حماية البيانات والخصوصية على تجربة خدمة العملاء لا سيما عبر القنوات
الرقمية. فعلى سبيل المثال عندما يتصل العميل للاستفسار عن رصيده يطلب منه المرور
بعدة خطوات للتحقق من هويته وفقًا للوائح المعمول بها. يضمن هذا الإجراء سرية
المعلومات ويمنع إساءة استخدامها، إلا أن بعض العملاء قد يرونه معقدا أو تأخيرا
في الخدمة. يكمن جوهر المشكلة هنا في غياب التوازن الدقيق بين الأمن وكفاءة الخدمة،
إذ يمكن للتكنولوجيا الذكية تقليل وقت التحقق دون المساس بالمتطلبات القانونية."

📌 لماذا هذا يستحق MERIT:
  ✓ يشرح لماذا: اللائحة ← تفرض خطوات تحقق
  ✓ يكشف الأثرين (إيجابي + سلبي): حماية + تأخير محتمل
  ✓ يحدد جوهر التعارض بتفكير نقدي: الأمن vs الكفاءة
  ✓ يقترح حلاً مبنياً على السبب (التكنولوجيا الذكية)
  ✗ لا يصل إلى حكم تقييمي نهائي مع ترجيح (هذا مطلوب للـ DISTINCTION)
────────────────────────────────────────────────────────"""

# ──────────────────────────────────────────────────────
# DISTINCTION — مثال حقيقي من D.2  (تقييم فوائد التحسين — حكمة)
# ──────────────────────────────────────────────────────
DISTINCTION_EXEMPLAR_AR = """\
مثال حقيقي على إجابة حققت مستوى DISTINCTION  (قيِّم / برِّر / استنتج):
────────────────────────────────────────────────────────
السياق: طُلب من الطالب أن يقيّم فوائد تحسين خدمة العملاء للشركة والعميل والموظف.

[ما كتبه الطالب — هذا النص هو DISTINCTION]:
"العلاقة المتبادلة بين تحسين الخدمة ورضا العملاء وأداء الشركة:
عندما تتحسن سرعة الاستجابة ودقة المعلومات المقدمة للعملاء، يزداد رضاهم وثقتهم
بالشركة. وهذا بدوره يؤدي إلى استمرار التعاملات التجارية وزيادة حجم الطلبات،
مما يؤثر بشكل مباشر على الأداء المالي للشركة.
الأثر المترابط: رضا العملاء ← زيادة الولاء ← نمو المبيعات وتحسين الأرباح.

قد يؤدي تقديم خدمة ممتازة دون الالتزام باللوائح إلى تجربة إيجابية مؤقتة ولكنه
يعرض الشركة لمخاطر قانونية كبيرة. أما الالتزام الكامل دون خدمة جيدة فيضفي
مصداقية قانونية ولكنه يعجز عن جذب العملاء أو الاحتفاظ بهم. النموذج الأمثل هو
الجمع بين الأمرين: تقديم خدمات سريعة ومهنية ضمن إطار قانوني واضح.

يمكن الاستنتاج أن تحسين خدمة العملاء يمثل استثمارًا استراتيجيًا وليس تكلفة
تشغيلية يخلق حلقة إيجابية متكاملة بين الشركة والعميل والموظف في آن واحد."

📌 لماذا هذا يستحق DISTINCTION:
  ✓ حكم مبرر واضح: "استثمار استراتيجي وليس تكلفة" — وليس مجرد وصف للفوائد
  ✓ يقيّم البدائل نقدياً: خدمة بدون لوائح vs لوائح بدون خدمة ← الحكم: الجمع هو الأمثل
  ✓ يربط سلاسل تأثير متعددة المستويات: خدمة→رضا→ولاء→أرباح
  ✓ استنتاج معلل نهائي يتجاوز التحليل إلى ترجيح ومبرر
  ✓ التقييم ليس على طرف واحد — بل يلحظ المقايضات ويرجّح
────────────────────────────────────────────────────────"""


def get_calibration_block(band: str) -> str:
    """
    يعيد مقطع المعايرة المناسب للمستوى المطلوب.
    يُضاف إلى prompt التقييم لمساعدة النموذج على فهم المستوى المطلوب فعلياً.

    Args:
        band: "PASS"، "MERIT"، أو "DISTINCTION"

    Returns:
        نص المعايرة المنسق جاهز للإدراج في الـ prompt، أو سلسلة فارغة.
    """
    exemplar_map = {
        "PASS":        PASS_EXEMPLAR_AR,
        "MERIT":       MERIT_EXEMPLAR_AR,
        "DISTINCTION": DISTINCTION_EXEMPLAR_AR,
    }
    exemplar = exemplar_map.get(band, "")
    if not exemplar:
        return ""

    return f"""
╔══════════════════════════════════════════════════════════════╗
║   📐 معايرة المستوى — ما يبدو عليه {band} في الواقع الفعلي   ║
╚══════════════════════════════════════════════════════════════╝

⚠️  الغرض من هذا المثال: معايَرة مستوى توقعك — ليس مقارنة كلمة بكلمة.
    انظر إلى: عمق التفكير، نوع الربط، طريقة تقديم الحكم.
    ولا تنظر إلى: الموضوع بالضبط أو عدد الكلمات أو أسلوب الكتابة.

{exemplar}

🔑 طبّق هذا المستوى من التفكير (وليس الكلمات أو الموضوع بالضبط)
   عند تقييم إجابة الطالب في المرحلة 3 أدناه.
"""
